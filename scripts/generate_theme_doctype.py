"""Regenerate the ForceX Theme Settings DocType JSON from theme_engine.SECTIONS.

Adding or changing a setting:
  1. edit SECTIONS in sas_forcex/theme_engine.py (label, default, light/dark twin)
  2. python scripts/generate_theme_doctype.py      (from apps/sas_forcex)
  3. use the new --fxh-* token in public/css/forcex_harbour.bundle.css
  4. bench --site <site> migrate   (then Clear Cache on the settings page)

tests/test_theme_doctype_schema.py fails until step 2 has been run, so the form,
the defaults and the CSS can never quietly disagree.
"""

