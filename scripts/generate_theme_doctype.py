def write(path: Path, data: dict):
	path.parent.mkdir(parents=True, exist_ok=True)
	path.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
	print("wrote", path.relative_to(ROOT))


HARBOUR_CSS = ROOT / "sas_forcex" / "public" / "css" / "forcex_harbour.bundle.css"
START = "/* fxh:defaults:start — generated by scripts/generate_theme_doctype.py, do not edit */\n"
END = "/* fxh:defaults:end */"


def write_default_tokens():
	"""Bake the default palette into the stylesheet (between the markers, or at the top)."""
	css = HARBOUR_CSS.read_text(encoding="utf-8")
	block = START + te.default_tokens_css() + END
	if "/* fxh:defaults:start" in css:
		head, rest = css.split("/* fxh:defaults:start", 1)
		css = head + block + rest.split(END, 1)[1]
	else:
		# right after the file's header comment
		header_end = css.index("*/") + 2
		css = css[:header_end] + "\n\n" + block + css[header_end:]
	HARBOUR_CSS.write_text(css, encoding="utf-8")
	print("wrote", HARBOUR_CSS.relative_to(ROOT), "(default tokens)")


if __name__ == "__main__":
	write(DOCTYPE_DIR / "forcex_theme_settings" / "forcex_theme_settings.json", settings_doctype())
	write(DOCTYPE_DIR / "forcex_theme_role" / "forcex_theme_role.json", role_row_doctype())
	write_default_tokens()
